export type MessageKey = keyof (typeof messages)['en'];

/** The message `key` in `locale`, with `{name}` slots filled from `values`. */
export function message(locale: Locale, key: MessageKey, values: Readonly<Record<string, string | number>> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (slot, name: string) => (name in values ? String(values[name]) : slot));
}
